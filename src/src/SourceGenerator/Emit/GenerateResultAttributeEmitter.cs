using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Purview.Results.SourceGeneration.Helpers;
using System.Text;

namespace Purview.Results.SourceGeneration.Emit;

/// <summary>
/// Emits the <c>GenerateResultAttribute</c> that consumers apply to their unions.
/// </summary>
static class GenerateResultAttributeEmitter
{
	/// <summary>
	/// Emits the opt-in attribute through the post-initialization output, so every compilation that
	/// references the generator has the attribute without declaring it or referencing another package.
	/// </summary>
	/// <param name="context">The post-initialization context to add the generated source to.</param>
	public static void EmitAttribute(IncrementalGeneratorPostInitializationContext context)
	{
		CodeWriter writer = new(GenerationSettings.Create<ResultsSourceGenerator>());

		writer.AutoGeneratedHeader();
		writer.FileScopedNamespace(PropertyLibrary.SourceGenerationNamespace);

		writer.XmlSummary(
			"Opts a C# 15 union declaration into result helper generation.",
			$"Applying this attribute to a union declaration causes strongly typed helpers to be generated for each of the union's case types, so a case can be converted into a {XmlInlineCode(DocText.Escape(PropertyLibrary.ResultTypeName))} with a single call."
		);
		writer.XmlRemarks(
			$"The attribute is generated into every compilation that references the generator, so it is never declared by hand. Applying it to a type that is not a union is reported as {XmlInlineCode("RSG1000")}."
		);

		writer.AttributeClass(
			PropertyLibrary.GenerateResultAttributeName,
			TypeDeclarationAccessibility.Public,
			AttributeTargets.Class | AttributeTargets.Struct | AttributeTargets.Enum | AttributeTargets.Interface,
			body => body.Comment("Apply this attribute to a C# union declaration to generate its result helpers."),
			inherited: false,
			allowMultiple: false,
			configure: options => options with { IsPartial = false }
		);

		context.AddSource(PropertyLibrary.AttributeHintName, SourceText.From(writer.ToString(), Encoding.UTF8));
	}
}
