// Demonstrates Purview.Unions and Purview.Results in one compilation over the Tenancy domain the package
// README documents.
//
//   dotnet run --project src/src/Examples.Unions
//
// The union generator emits the C# 15 custom union shape with typed case storage; the results generator sees
// only the source-visible case list and emits the AsFailure helpers and the union-receiver factories. Neither
// generator is aware of the other's output, and Purview.Results never references Purview.Unions.

TenantDirectory directory = new();
TenantId acmeId = new("acme");
TenantId globexId = new("globex");
TenantId missingId = new("initech");

Heading("1. A union generated by Purview.Unions is the error type of a result");

ShowResult("Find(acme)", directory.Find(acmeId));
ShowResult("Find(globex)", directory.Find(globexId));
ShowResult("Find(initech)", directory.Find(missingId));

Heading("2. The generated AsFailure helper converts a case for a different success type");

TenantNotFound notFound = new(missingId);

ShowResult("AsFailure<Tenant>()", notFound.AsFailure<Tenant>());

Heading("3. The union-receiver factory names the union, so a shared case stays unambiguous");

ShowResult("TenantError.Failure<Tenant>()", TenantError.Failure<Tenant>(notFound));
ShowUnit("TenantError.Failure()", TenantError.Failure(notFound));

Heading("4. TryGetValue probes the active case without boxing");

var failure = directory.Find(missingId).Error;

if (failure.TryGetValue(out TenantNotFound activeNotFound))
	Show("TryGetValue(TenantNotFound)", activeNotFound.TenantId.Value);

Show("HasValue", failure.HasValue);

Heading("5. The union is exhaustive over its cases");

// A generated union is a compiler union on net11.0, so the switch covers the case types and needs no
// discard arm. A struct union can also be empty, which the null arm covers.
Console.WriteLine($"  switch -> {DescribeError(failure)}");

Heading("6. A unit result deletes a tenant or reports the same union case");

ShowUnit("Delete(acme)", directory.Delete(acmeId));
ShowUnit("Delete(acme) again", directory.Delete(acmeId));

static void Heading(string title)
{
	Console.WriteLine();
	Console.WriteLine(title);
	Console.WriteLine(new string('-', title.Length));
}

static void Show(string label, object? value) => Console.WriteLine($"  {label, -32} -> {value}");

static void ShowResult<TValue>(string label, Result<TValue, TenantError> result)
{
	var text = result.Match(value => $"Success({value})", DescribeError);

	Console.WriteLine($"  {label, -32} -> {text}");
}

static void ShowUnit(string label, Result<TenantError> result)
{
	// A unit result's success arm takes no value; only the failure arm receives the error.
	var text = result.Match(() => "Success", DescribeError);

	Console.WriteLine($"  {label, -32} -> {text}");
}

static string DescribeError(TenantError error) =>
	error switch
	{
		TenantNotFound notFound => $"TenantNotFound({notFound.TenantId.Value})",
		TenantDisabled disabled => $"TenantDisabled({disabled.TenantId.Value})",
		TenantAlreadyExists exists => $"TenantAlreadyExists({exists.TenantId.Value})",
		null => "empty",
	};
